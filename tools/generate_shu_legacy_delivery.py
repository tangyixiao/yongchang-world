"""Render SHU legacy popup round-robin triggers; pass --check to verify."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "yongchang_world/common/scripted_triggers/ywc_shu_legacy_delivery_triggers.txt"
CANDIDATES = [
 ("ywc_je_eternal_yongchang", "NOT = { has_variable = ywc_eternal_yongchang_resolved } NOT = { has_variable = ywc_eternal_yongchang_pending }"),
 ("ywc_je_who_inherits_china", "NOT = { has_variable = ywc_shared_direction_chosen }"),
 ("ywc_je_yongchang_century", "NOT = { has_variable = ywc_je_yongchang_century_resolved } NOT = { has_variable = ywc_je_yongchang_century_failed }"),
 ("ywc_je_shu_scholar_merchants", "NOT = { has_variable = ywc_je_shu_scholar_merchants_resolved } NOT = { has_variable = ywc_je_shu_scholar_merchants_failed }"),
 ("ywc_je_shu_blackwater_frontier", "NOT = { has_variable = ywc_je_shu_blackwater_frontier_resolved } NOT = { has_variable = ywc_je_shu_blackwater_frontier_failed }"),
 ("ywc_je_shu_opium_question", "NOT = { has_variable = ywc_je_shu_opium_question_resolved } NOT = { has_variable = ywc_je_shu_opium_question_failed }"),
 ("ywc_route_shu_bureaucratic_integration", "NOT = { has_variable = ywc_route_shu_bureaucratic_integration_success } NOT = { has_variable = ywc_route_shu_bureaucratic_integration_failure } NOT = { has_variable = ywc_route_shu_bureaucratic_integration_abandonment_cooldown }"),
 ("ywc_route_shu_customs_reform", "NOT = { has_variable = ywc_route_shu_customs_reform_success } NOT = { has_variable = ywc_route_shu_customs_reform_failure } NOT = { has_variable = ywc_route_shu_customs_reform_abandonment_cooldown }"),
]

CHAPTERS = ((1, 9, 100), (2, 10, 105), (3, 11, 110))

def chapter_predicate(chapter, first):
    outstanding = ' '.join(
        f"NOT = {{ has_variable = ywc_campaign_shu_c{chapter}_e{n}_done }}"
        for n in range(first, first + 5))
    return (f"ywc_shu_legacy_chapter_base_{chapter} = yes "
            f"OR = {{ NOT = {{ has_variable = ywc_campaign_national_wait }} var:ywc_campaign_national_wait <= 0 }} "
            f"OR = {{ NOT = {{ has_variable = ywc_campaign_shu_c{chapter}_prelude }} {outstanding} }}")

CANDIDATES += [(f"ywc_je_flavor_shu_court_{chapter}", chapter_predicate(chapter, first))
               for chapter, _, first in CHAPTERS]

def render():
    out = ["# Generated by tools/generate_shu_legacy_delivery.py; keep candidate predicates in sync with the legacy journals.\n"]
    for chapter, _, _ in CHAPTERS:
        v03 = "NOT = { has_variable = ywc_v03_shu_v03_shu_fiscal_register_started }" if chapter == 1 else ""
        out.append(f"ywc_shu_legacy_chapter_base_{chapter} = {{ is_country_alive = yes has_journal_entry = ywc_je_flavor_shu_court_{chapter} NOT = {{ has_variable = ywc_campaign_shu_c{chapter}_outcome }} {v03} }}\n")
    for index, (je, predicate) in enumerate(CANDIDATES, 1):
        out.append(f"ywc_shu_legacy_candidate_{index} = {{ is_country_alive = yes has_journal_entry = {je} {predicate} }}\n")
    for target in range(1, 12):
        out.append(f"ywc_shu_legacy_turn_{target} = {{\n ywc_shu_legacy_candidate_{target} = yes\n NOT = {{ has_variable = ywc_v03_major_event_cooldown }}\n NOT = {{ has_variable = ywc_shu_legacy_backoff }}\n OR = {{\n")
        for cursor in range(12):
            order = list(range(1, 12)) if cursor == 0 else list(range(cursor + 1, 12)) + list(range(1, cursor + 1))
            earlier = order[:order.index(target)]
            exclusions = ' '.join(f"NOT = {{ ywc_shu_legacy_candidate_{i} = yes }}" for i in earlier)
            out.append(f"  AND = {{ var:ywc_shu_legacy_cursor = {cursor} {exclusions} }}\n")
        out.append(" }\n}\n")
    for index, (je, _) in enumerate(CANDIDATES[:8], 1):
        epoch = f"ywc_shu_legacy_popup_epoch_{index}"
        # Bootstrap's pending flag is set by actual dispatch; unlike candidacy,
        # it must remain valid while its own window is open.
        eligibility = ("is_country_alive = yes has_journal_entry = ywc_je_eternal_yongchang NOT = { has_variable = ywc_eternal_yongchang_resolved }" if index == 1 else f"ywc_shu_legacy_candidate_{index} = yes")
        # Variable-only guards: correctness must not depend on numeric scopes
        # saved by save_scope_value_as being inherited across trigger_event,
        # which vanilla 1.13.11 scripts never rely on and the engine does not
        # document. A live request is (epoch recorded AND request window live);
        # the pre-delivery fallback (no epoch recorded) keeps non-dispatch
        # legacy paths working exactly as before.
        old_window = f"NOT = {{ has_variable = {epoch} }}"
        request = f"OR = {{ AND = {{ has_variable = {epoch} has_variable = ywc_shu_legacy_request_live_{index} }} {old_window} }}"
        choice = f"OR = {{ AND = {{ has_variable = {epoch} has_variable = ywc_shu_legacy_delivered_epoch_{index} var:ywc_shu_legacy_delivered_epoch_{index} ?= var:{epoch} }} {old_window} }}"
        request_guard = f"AND = {{ {eligibility} {request} }}"
        choice_guard = f"AND = {{ {eligibility} {choice} }}"
        if index == 2:
            request_guard = f"OR = {{ NOT = {{ c:SHU ?= this }} {request_guard} }}"
            choice_guard = f"OR = {{ NOT = {{ c:SHU ?= this }} {choice_guard} }}"
        out.append(f"ywc_shu_legacy_request_valid_{index} = {{ {request_guard} }}\n")
        out.append(f"ywc_shu_legacy_choice_valid_{index} = {{ {choice_guard} }}\n")
    # Each chapter occupies one fair slot; every prelude and continuation has
    # an independent dispatch/receipt identity, preserving old save choices.
    for chapter, slot, first in CHAPTERS:
        for offset in range(6):
            index = 9 + (chapter - 1) * 6 + offset
            epoch = f"ywc_shu_legacy_popup_epoch_{index}"
            if offset == 0:
                stage = f"NOT = {{ has_variable = ywc_campaign_shu_c{chapter}_prelude }}"
            else:
                number = first + offset - 1
                prior = " ".join(f"has_variable = ywc_campaign_shu_c{chapter}_e{n}_done" for n in range(first, number))
                stage = f"has_variable = ywc_campaign_shu_c{chapter}_prelude {prior} NOT = {{ has_variable = ywc_campaign_shu_c{chapter}_e{number}_done }}"
            phase = f"ywc_shu_legacy_chapter_base_{chapter} = yes {stage}"
            out.append(f"ywc_shu_legacy_phase_{index} = {{ {phase} }}\n")
            out.append(f"ywc_shu_legacy_dispatch_{index} = {{ ywc_shu_legacy_turn_{slot} = yes ywc_shu_legacy_phase_{index} = yes }}\n")
            old_window = f"NOT = {{ has_variable = {epoch} }}"
            request = f"OR = {{ AND = {{ has_variable = {epoch} has_variable = ywc_shu_legacy_request_live_{index} }} {old_window} }}"
            choice = f"OR = {{ AND = {{ has_variable = {epoch} has_variable = ywc_shu_legacy_delivered_epoch_{index} var:ywc_shu_legacy_delivered_epoch_{index} ?= var:{epoch} }} {old_window} }}"
            out.append(f"ywc_shu_legacy_request_valid_{index} = {{ ywc_shu_legacy_phase_{index} = yes {request} }}\n")
            out.append(f"ywc_shu_legacy_choice_valid_{index} = {{ ywc_shu_legacy_phase_{index} = yes {choice} }}\n")
    return ''.join(out)

if __name__ == '__main__':
    expected = render()
    if '--check' in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8-sig') != expected:
            raise SystemExit('SHU legacy delivery triggers are stale')
    else:
        OUTPUT.write_text(expected, encoding='utf-8')
